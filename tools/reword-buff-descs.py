def main():
    text = PATH.read_text(encoding='utf-8')
    misses = []
    for old, new in PAIRS:
        cnt = text.count(old)
        if cnt != 1:
            misses.append((cnt, old[:60]))
        else:
            text = text.replace(old, new)
    if misses:
        for cnt, frag in misses:
            print('MISS(%d): %s' % (cnt, frag))
        sys.exit(1)
    import io
    with io.open(PATH, 'w', encoding='utf-8', newline='') as fh:  # 不做行尾翻译，保持 LF
        fh.write(text)
    print('DONE: %d 条 desc 已改写' % len(PAIRS))


if __name__ == '__main__':
    main()
