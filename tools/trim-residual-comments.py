def main():
    for rel, pairs in EDITS:
        path = ROOT / rel
        with open(path, 'r', encoding='utf-8', newline='') as fh:
            text = fh.read()
        for old, new in pairs:
            if old == new:
                continue
            cnt = text.count(old)
            if cnt != 1:
                print('FAIL %s: 匹配 %d 处 → %r' % (rel, cnt, old[:50]))
                sys.exit(1)
            text = text.replace(old, new)
        with open(path, 'w', encoding='utf-8', newline='') as fh:
            fh.write(text)
        print('DONE %s（%d 处）' % (rel, len([p for p in pairs if p[0] != p[1]])))


if __name__ == '__main__':
    main()
