def main():
    text = PATH.read_text(encoding='utf-8')
    misses = []
    for old, new in PAIRS:
        cnt = text.count(old)
        if cnt != 1:
            misses.append((cnt, old[:70]))
        else:
            text = text.replace(old, new)
    if misses:
        for cnt, frag in misses:
            print('MISS(%d): %s' % (cnt, frag))
        sys.exit(1)
    with io.open(PATH, 'w', encoding='utf-8', newline='') as fh:   # 保持 LF
        fh.write(text)
    print('DONE: %d 条 desc 已补成具体数值' % len(PAIRS))
    return 0


if __name__ == '__main__':
    sys.exit(main())
